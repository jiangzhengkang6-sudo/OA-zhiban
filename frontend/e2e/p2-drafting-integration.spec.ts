import { expect, test, type Page } from '@playwright/test'

async function fits(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  const main = page.locator('.draft-workbench')
  const box = await main.boundingBox()
  expect(box?.width).toBeGreaterThan(250)
  expect(await main.locator('h1').innerText()).not.toBe('')
}

function recordTraffic(page: Page) {
  const writes: string[] = [], errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    if (['POST', 'PATCH', 'PUT', 'DELETE'].includes(request.method())) writes.push(new URL(request.url()).pathname)
  })
  return { writes, errors }
}

async function reopenFromTasks(page: Page, scene: string) {
  const recordUrl = new URL(page.url()).pathname, businessId = recordUrl.split('/').pop()!
  await page.goto('/tasks?scene=' + scene)
  const task = page.locator('.task-card').filter({ has: page.getByRole('heading', { name: businessId, exact: true }) })
  await task.getByTestId('open-task').click()
  await expect(page).toHaveURL(new RegExp(recordUrl + '$'))
}

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('oa_current_user', 'u_emp_001'))
})

test('document creates, generates, saves, compares and confirms through the real API', async ({ page }, info) => {
  const traffic = recordTraffic(page), title = `文档验收 ${Date.now()} ${info.project.name}`
  await page.goto('/documents')
  await page.getByRole('textbox', { name: '标题', exact: true }).fill(title)
  await page.getByRole('textbox', { name: '接收对象' }).fill('项目组')
  await page.getByRole('textbox', { name: '期限' }).fill('2026-10-20')
  await page.getByRole('textbox', { name: '依据材料' }).fill('验收计划')
  await page.getByRole('textbox', { name: '核心要点' }).fill('请各组提交项目验收材料。')
  await page.getByRole('textbox', { name: '分发范围' }).fill('项目组内部')
  await fits(page)
  const created = page.waitForResponse(r => r.url().endsWith('/api/documents') && r.request().method() === 'POST')
  await page.getByTestId('create-draft').click()
  expect((await created).status()).toBe(200)
  await expect(page).toHaveURL(/\/documents\/DOC-/)
  const generated = page.waitForResponse(r => r.url().endsWith('/generate') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '生成草稿', exact: true }).click()
  expect((await generated).status()).toBe(200)
  const editor = page.getByRole('textbox', { name: '文档正文' })
  await expect(editor).not.toBeEmpty()
  const initial = await editor.inputValue(), edited = initial + '\n人工核对：按计划提交。'
  await editor.fill(edited)
  await expect(page.getByTestId('confirm-draft')).toBeDisabled()
  const saved = page.waitForResponse(r => r.url().endsWith('/draft') && r.request().method() === 'PATCH')
  await page.getByTestId('save-draft').click()
  expect((await saved).status()).toBe(200)
  await expect(page.locator('.heading')).toContainText('v2')
  await page.locator('.draft-history .el-select__wrapper').click()
  await page.getByRole('option', { name: 'v1', exact: true }).click()
  await expect(page.locator('.version-columns pre').first()).toHaveText(initial)
  await expect(page.locator('.version-columns pre').last()).toHaveText(edited)
  await fits(page)
  await page.screenshot({ path: info.outputPath('document-review.png'), fullPage: true })
  await page.getByTestId('metadata-confirmed').check()
  const confirmed = page.waitForResponse(r => r.url().endsWith('/decisions') && r.request().method() === 'POST')
  await page.getByTestId('confirm-draft').click()
  await page.getByRole('dialog', { name: '确认草稿', exact: true }).getByRole('button', { name: 'OK', exact: true }).click()
  expect((await confirmed).status()).toBe(200)
  await page.reload()
  await expect(editor).toHaveValue(edited)
  await expect(editor).toBeDisabled()
  await expect(page.getByTestId('confirm-draft')).toHaveCount(0)
  await expect(page.locator('.heading')).toContainText('已确认')
  await reopenFromTasks(page, 'document')
  await expect(editor).toHaveValue(edited)
  await expect(editor).toBeDisabled()
  expect(traffic.errors).toEqual([])
  expect(traffic.writes.every(path => path.startsWith('/api/documents'))).toBe(true)
})

test('mail preserves revisions and requires the separate sensitive confirmation', async ({ page }, info) => {
  const traffic = recordTraffic(page), title = `邮件验收 ${Date.now()} ${info.project.name}`
  await page.goto('/emails')
  await page.getByRole('textbox', { name: '主题', exact: true }).fill(title)
  await page.getByRole('textbox', { name: '发件人' }).fill('partner@example.com')
  await page.getByRole('textbox', { name: '收件人', exact: true }).fill('project@example.com')
  await page.getByRole('textbox', { name: '邮件原文' }).fill('请项目组整理验收材料。\n请于下周反馈结果。')
  await page.locator('.el-switch').filter({ has: page.getByRole('switch', { name: '涉及外部联系人' }) }).click()
  await expect(page.getByRole('switch', { name: '涉及外部联系人' })).toBeChecked()
  await page.getByRole('button', { name: '添加附件信息' }).click()
  await page.getByRole('textbox', { name: '附件名称' }).fill('验收清单.xlsx')
  await page.locator('.attachment-row .el-checkbox').filter({ has: page.getByRole('checkbox', { name: '敏感', exact: true }) }).click()
  await expect(page.getByRole('checkbox', { name: '敏感', exact: true })).toBeChecked()
  await fits(page)
  const created = page.waitForResponse(r => r.url().endsWith('/api/emails') && r.request().method() === 'POST')
  await page.getByTestId('create-draft').click()
  expect((await created).status()).toBe(200)
  await expect(page).toHaveURL(/\/emails\/MAIL-/)
  const analyzed = page.waitForResponse(r => r.url().endsWith('/analyze') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '分析邮件', exact: true }).click()
  expect((await analyzed).status()).toBe(200)
  const reply = page.getByRole('textbox', { name: '回复正文' })
  await expect(reply).not.toBeEmpty()
  const edited = '已收到材料要求，项目组将核对后反馈。'
  await reply.fill(edited)
  await expect(page.getByTestId('confirm-draft')).toBeDisabled()
  const saved = page.waitForResponse(r => r.url().endsWith('/draft') && r.request().method() === 'PATCH')
  await page.getByTestId('save-draft').click()
  expect((await saved).status()).toBe(200)
  await expect(page.locator('.heading')).toContainText('v2')
  await page.locator('.draft-history .el-select__wrapper').click()
  await page.getByRole('option', { name: 'v1', exact: true }).click()
  await expect(page.locator('.version-columns pre').first()).toContainText('分类：工作事项')
  await expect(page.locator('.version-columns pre').first()).toContainText('负责人候选：待确认')
  await expect(page.locator('.version-columns pre').last()).toContainText(edited)
  await fits(page)
  await page.screenshot({ path: info.outputPath('email-review.png'), fullPage: true })
  await page.getByTestId('metadata-confirmed').check()
  await expect(page.getByTestId('confirm-draft')).toBeDisabled()
  await page.getByTestId('warnings-acknowledged').check()
  await page.getByTestId('confirm-draft').click()
  await page.getByRole('dialog', { name: '确认草稿', exact: true }).getByRole('button', { name: 'OK', exact: true }).click()
  const secondary = page.getByRole('dialog', { name: '二次确认', exact: true })
  await expect(secondary).toBeVisible()
  await secondary.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(traffic.writes.filter(path => path.endsWith('/decisions'))).toHaveLength(0)
  await page.getByTestId('confirm-draft').click()
  await page.getByRole('dialog', { name: '确认草稿', exact: true }).getByRole('button', { name: 'OK', exact: true }).click()
  const confirmed = page.waitForResponse(r => r.url().endsWith('/decisions') && r.request().method() === 'POST')
  await page.getByRole('dialog', { name: '二次确认', exact: true }).getByRole('button', { name: 'OK', exact: true }).click()
  const response = await confirmed
  expect(response.status()).toBe(200)
  expect((await response.json()).data).toMatchObject({ status: 'CONFIRMED', version: 2, external_writes: false })
  await page.reload()
  await expect(reply).toHaveValue(edited)
  await expect(reply).toBeDisabled()
  await expect(page.getByTestId('confirm-draft')).toHaveCount(0)
  await reopenFromTasks(page, 'email')
  await expect(reply).toHaveValue(edited)
  await expect(reply).toBeDisabled()
  expect(traffic.errors).toEqual([])
  expect(traffic.writes.every(path => path.startsWith('/api/emails'))).toBe(true)
})
