import { test, expect, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'
const credential=readFileSync('../data/verification/m1/preview-login.txt','utf8')
const password=credential.match(/密码：([^\r\n]+)/)![1]
async function login(page:Page,username='m1_admin',secret=password) {
  await page.goto('/login')
  await page.getByLabel('账号',{exact:true}).fill(username)
  await page.getByLabel('密码',{exact:true}).fill(secret)
  const issued=page.waitForResponse(r=>r.url().endsWith('/api/auth/login') && r.request().method()==='POST')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  const response=await issued
  expect(response.status()).toBe(200)
  return (await response.json()).data.access_token as string
}
test('桌面组织管理、刷新恢复、越权及停用撤销',async ({page,browser}) => {
  await page.goto('/organization')
  await expect(page).toHaveURL(/\/login/)
  const token=await login(page)
  await expect(page.getByRole('heading',{name:'组织管理',exact:true})).toBeVisible()
  await expect(page.getByText('开发演示账号',{exact:true})).toHaveCount(0)
  await page.getByRole('tab',{name:'部门',exact:true}).click()
  await page.getByRole('button',{name:'新增部门'}).click()
  const department='验收部门'+Date.now()
  await page.getByLabel('名称',{exact:true}).fill(department)
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await expect(page.getByRole('cell',{name:department,exact:true})).toBeVisible()
  await page.getByRole('tab',{name:'成员',exact:true}).click()
  await page.getByRole('button',{name:'新增成员'}).click()
  const username='browser'+Date.now()
  const employeePassword='Browser-test-password-123!'
  await page.getByLabel('姓名',{exact:true}).fill('浏览器验收员工')
  await page.getByLabel('账号',{exact:true}).fill(username)
  await page.getByLabel('初始密码',{exact:true}).fill(employeePassword)
  await page.getByRole('button',{name:'保存',exact:true}).click()
  const row=page.getByRole('row').filter({has:page.getByRole('cell',{name:username,exact:true})})
  await expect(row).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading',{name:'组织管理',exact:true})).toBeVisible()
  const storage=await page.evaluate(()=>JSON.stringify([localStorage,sessionStorage]))
  expect(storage).not.toContain(token)
  const cookies=await page.context().cookies()
  expect(cookies.find(c=>c.name==='oa_refresh')?.httpOnly).toBe(true)
  const employee=await browser.newContext({baseURL:'http://127.0.0.1:5193'})
  const empPage=await employee.newPage()
  await login(empPage,username,employeePassword)
  await expect(empPage).toHaveURL(/\/tasks/)
  await empPage.goto('/organization')
  await expect(empPage).toHaveURL(/\/tasks/)
  await expect(empPage.getByRole('menuitem',{name:'组织管理'})).toHaveCount(0)
  await row.getByRole('button',{name:'编辑',exact:true}).click()
  await page.getByText('停用',{exact:true}).last().click()
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await page.getByRole('button',{name:'停用',exact:true}).click()
  await expect(row.getByText('待交接',{exact:true})).toBeVisible()
  await empPage.reload()
  await expect(empPage).toHaveURL(/\/login/)
  await employee.close()
  await page.screenshot({path:'../data/verification/m1/organization-desktop.png',fullPage:true})
  await page.getByRole('button',{name:'退出登录',exact:true}).click()
  await expect(page).toHaveURL(/\/login/)
  await page.goto('/organization')
  await expect(page).toHaveURL(/\/login/)
})
test('手机登录、组织弹窗和退出',async ({page})=>{
  await page.setViewportSize({width:390,height:844})
  await login(page)
  await expect(page.getByRole('heading',{name:'组织管理',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'新增成员'}).click()
  const box=await page.getByRole('dialog').boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x+box!.width).toBeLessThanOrEqual(391)
  await page.getByRole('button',{name:'取消',exact:true}).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.screenshot({path:'../data/verification/m1/organization-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'退出登录',exact:true}).click()
  await expect(page).toHaveURL(/\/login/)
  await page.screenshot({path:'../data/verification/m1/login-mobile.png',fullPage:true})
})
