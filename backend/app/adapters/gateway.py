"""Asynchronous bridge contract between agent orchestration and formal OA services."""

from dataclasses import dataclass
from typing import Any, Protocol

from sqlalchemy.ext.asyncio import AsyncSession

from ..core.context import CurrentUser, get_trace_id
from ..schemas.oa_bridge import BridgeApprovalDecision, BridgeLeaveEdit, BridgeLeaveSubmit, BridgeNotification
from ..schemas.oa_ticket import FormalTicketProposal


@dataclass(frozen=True)
class BridgeContext:
    """Trusted request state shared by every gateway call in one graph run."""

    actor: CurrentUser
    session: AsyncSession
    trace_id: str = ""
    confirmation_id: str | None = None

    def __post_init__(self) -> None:
        if not self.trace_id:
            object.__setattr__(self, "trace_id", get_trace_id())


class OAGateway(Protocol):
    async def get_user_context(self, user_id: str | None = None) -> dict[str, Any]: ...
    async def get_leave_case(self, business_id: str) -> dict[str, Any]: ...
    async def get_leave_balance(self, user_id: str | None = None, leave_type: str | None = None) -> list[dict[str, Any]]: ...
    async def get_approval_route(self, business_id: str) -> dict[str, Any]: ...
    async def create_or_update_approval(self, command: BridgeLeaveSubmit | BridgeApprovalDecision | dict[str, Any]) -> dict[str, Any]: ...
    async def get_approval_result(self, idempotency_key: str) -> dict[str, Any] | None: ...
    async def edit_leave_case(self, command: BridgeLeaveEdit | dict[str, Any]) -> dict[str, Any]: ...
    async def get_leave_edit_result(self, idempotency_key: str) -> dict[str, Any] | None: ...
    async def create_or_merge_ticket(self, command: FormalTicketProposal | dict[str, Any]) -> dict[str, Any]: ...
    async def get_ticket_result(self, idempotency_key: str) -> dict[str, Any] | None: ...
    async def notify(self, command: BridgeNotification | dict[str, Any]) -> dict[str, Any]: ...
    async def get_notification_result(self, idempotency_key: str) -> dict[str, Any] | None: ...
    async def capabilities(self) -> dict[str, Any]: ...
    async def get_ticket_status(self, ticket_id: str) -> dict[str, Any]: ...
    async def get_field_dict(self) -> dict[str, Any]: ...

